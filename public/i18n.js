function t(key, args = {}) {
    const message = language === 'nl' ? dutchMessages[key] || key : key;
    return message.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(args, name) ? String(args[name]) : match);
}

function translateError(message) {
    if (typeof message !== 'string') return message;
    if (Object.hasOwn(dutchMessages, message)) return t(message);
    for (const [key, translated] of Object.entries(dutchMessages)) {
        if (translated === message) return t(key);
        if (!key.includes('{')) continue;
        for (const template of [key, translated]) {
            const names = [];
            const pattern = template.split(/(\{\w+\})/).map(part => {
                if (/^\{\w+\}$/.test(part)) { names.push(part.slice(1, -1)); return '(.+?)'; }
                return part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
            }).join('');
            const match = message.match(new RegExp(`^${pattern}$`));
            if (match) return t(key, Object.fromEntries(names.map((name, i) => [name, match[i + 1]])));
        }
    }
    return message;
}

function uiLocale() { return language === 'nl' ? 'nl-NL' : 'en-GB'; }

function countLabel(count, singular, plural) { return t(count === 1 ? singular : plural, { count }); }

function applyTranslations() {
    document.documentElement.lang = language;
    document.querySelectorAll('[data-i18n]').forEach(node => { node.textContent = t(node.dataset.i18n); });
    document.querySelectorAll('[data-i18n-html]').forEach(node => { node.innerHTML = t(node.dataset.i18nHtml); });
    for (const attribute of ['placeholder', 'aria-label', 'title']) {
        document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(node => {
            node.setAttribute(attribute, t(node.getAttribute(`data-i18n-${attribute}`)));
        });
    }
    document.getElementById('language').value = language;
}

document.addEventListener('DOMContentLoaded', () => {
    applyTranslations();
    document.getElementById('language').addEventListener('change', event => {
        language = event.target.value === 'nl' ? 'nl' : 'en';
        try { localStorage.setItem('crossban-review-language', language); } catch {}
        applyTranslations();
        document.dispatchEvent(new Event('ui-language-change'));
    });
});
